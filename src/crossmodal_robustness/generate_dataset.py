"""Deterministically generate a controlled synthetic image dataset.

The rendered images are original, generated by this repository. No third-party
photographs, image-generation models, or unverified annotation licenses are used.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import math
import random
from pathlib import Path

from PIL import Image, ImageDraw

from .dataset import COLORS, SHAPES

PALETTE = {
    "red": (213, 53, 65),
    "blue": (48, 109, 207),
    "green": (49, 153, 97),
    "yellow": (231, 179, 39),
}
SEED = 20261105
SIZE = 256
VARIANTS_PER_COMBINATION = 6


def _vertices(shape: str, cx: float, cy: float, radius: float, angle: float):
    if shape == "square":
        count, shift = 4, math.pi / 4
    elif shape == "triangle":
        count, shift = 3, -math.pi / 2
    elif shape == "star":
        return [
            (
                cx + (radius if index % 2 == 0 else radius * 0.48) * math.cos(angle - math.pi / 2 + index * math.pi / 5),
                cy + (radius if index % 2 == 0 else radius * 0.48) * math.sin(angle - math.pi / 2 + index * math.pi / 5),
            )
            for index in range(10)
        ]
    else:
        raise ValueError(shape)
    return [
        (cx + radius * math.cos(angle + shift + index * 2 * math.pi / count),
         cy + radius * math.sin(angle + shift + index * 2 * math.pi / count))
        for index in range(count)
    ]


def render_image(color: str, shape: str, *, seed: int) -> Image.Image:
    """Draw one large unambiguous figure on a subtly varied background."""
    rng = random.Random(seed)
    base = rng.randint(239, 251)
    image = Image.new("RGB", (SIZE, SIZE), (base, base, min(255, base + 2)))
    draw = ImageDraw.Draw(image)

    # Sparse, low-contrast marks create nuisance variation, not extra objects.
    for _ in range(18):
        x, y = rng.randint(4, 251), rng.randint(4, 251)
        rad = rng.randint(1, 3)
        shade = rng.randint(216, 237)
        draw.ellipse((x - rad, y - rad, x + rad, y + rad), fill=(shade, shade, shade))

    cx, cy = 128 + rng.randint(-11, 11), 128 + rng.randint(-11, 11)
    radius = rng.randint(76, 91)
    angle = rng.uniform(-0.22, 0.22)
    fill = PALETTE[color]
    outline = (38, 43, 52)
    if shape == "circle":
        draw.ellipse((cx - radius, cy - radius, cx + radius, cy + radius),
                     fill=fill, outline=outline, width=4)
    else:
        draw.polygon(_vertices(shape, cx, cy, radius, angle),
                     fill=fill, outline=outline, width=4)
    return image


def generate_dataset(output: Path, *, force: bool = False) -> dict[str, object]:
    manifest = output / "manifest.jsonl"
    if manifest.exists() and not force:
        raise FileExistsError(f"{manifest} exists; use --force to intentionally regenerate")
    images_dir = output / "images"
    images_dir.mkdir(parents=True, exist_ok=True)
    rng = random.Random(SEED)
    records = []
    preview_items = []
    index = 0

    for color_index, color in enumerate(COLORS):
        for shape_index, shape in enumerate(SHAPES):
            for variant in range(VARIANTS_PER_COMBINATION):
                item_id = f"item_{index:03d}"
                image = render_image(color, shape, seed=rng.randrange(2**32))
                relative = f"images/{item_id}.png"
                target = images_dir / f"{item_id}.png"
                image.save(target, optimize=True)
                record = {
                    "id": item_id,
                    "image": relative,
                    "split": "development" if variant < 4 else "test",
                    "color": color,
                    "shape": shape,
                    "wrong_color": COLORS[(color_index + 1 + variant % 3) % len(COLORS)],
                    "wrong_shape": SHAPES[(shape_index + 1 + variant % 3) % len(SHAPES)],
                    "sha256": hashlib.sha256(target.read_bytes()).hexdigest(),
                }
                records.append(record)
                if variant == 0:
                    preview_items.append(image)
                index += 1

    with manifest.open("w", encoding="utf-8") as handle:
        for record in records:
            handle.write(json.dumps(record, sort_keys=True) + "\n")

    # The 4x4 contact sheet is a quick visual sanity check for reviewers.
    sheet = Image.new("RGB", (SIZE * 4, SIZE * 4), "white")
    for item_index, image in enumerate(preview_items):
        sheet.paste(image, ((item_index % 4) * SIZE, (item_index // 4) * SIZE))
    sheet.save(output / "preview.png", optimize=True)

    metadata = {
        "name": "synthetic_v1",
        "generator": "crossmodal_robustness.generate_dataset",
        "seed": SEED,
        "image_size": [SIZE, SIZE],
        "count": len(records),
        "development_count": sum(r["split"] == "development" for r in records),
        "test_count": sum(r["split"] == "test" for r in records),
        "labels": {"color": list(COLORS), "shape": list(SHAPES)},
        "dataset_origin": "Original deterministic vector-like graphics rendered with Pillow; no external images",
        "license": "MIT (see project LICENSE)",
        "caution": "Synthetic, visually simple, and not representative of real-world VQA",
    }
    (output / "metadata.json").write_text(json.dumps(metadata, indent=2) + "\n", encoding="utf-8")
    return metadata


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=Path("data/synthetic_v1"))
    parser.add_argument("--force", action="store_true")
    args = parser.parse_args()
    print(json.dumps(generate_dataset(args.output, force=args.force), indent=2))


if __name__ == "__main__":
    main()

